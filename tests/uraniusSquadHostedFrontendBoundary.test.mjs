import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const client=read('database/synthetic-world/hosted-smoke-client.tsx')
const server=read('scripts/run-uranius-hosted-smoke.mjs')
const adapter=read('database/synthetic-world/club-dashboard-adapter.mjs')
const sql=read('database/synthetic-world/hosted-squad-preview-read_REVIEW_ONLY.sql')
const launcher=read('scripts/run-approved-overview-https-windows.ps1')
test('HTTPS Squad is opt-in and scoped to verified server subject only',()=>{
 assert.match(server,/URANIUS_SQUAD_READ_APPROVED === '1'/)
 assert.match(server,/readSquad: squadSql \? \(id\) =>/)
 assert.match(server,/input: .*verified_subject.*squadSql/)
 assert.match(adapter,/readSquad\(current\.subject\)/)
 assert.match(adapter,/projectSyntheticSquadPreview\(result, \{ ownerVerified: true \}\)/)
 assert.match(adapter,/Squad preview not connected/)
 assert.match(launcher,/URANIUS_SQUAD_READ_APPROVED = '1'/)
 // Both flags must be cleared by the launcher, regardless of their order.
 assert.match(launcher,/'URANIUS_SQUAD_READ_APPROVED'/)
 assert.match(launcher,/'URANIUS_SQUAD_UUID_READ_APPROVED'/)
 assert.match(launcher,/foreach \(\$name in @\(/)
 assert.match(launcher,/Remove-Item "Env:\$name" -ErrorAction SilentlyContinue/)
})
test('Squad preview only reads real RLS-filtered synthetic fields and never changes hosted data',()=>{
 assert.match(sql,/BEGIN READ ONLY;/)
 assert.match(sql,/ROLLBACK;\s*$/)
 assert.match(sql,/current_user <> 'uranius_smoke_reader'/)
 assert.match(sql,/pg_stat_ssl/)
 assert.match(sql,/uranius_game\.get_my_club_id\(\) IS NULL/)
 assert.match(sql,/FROM uranius_catalog\.riders r/)
 assert.doesNotMatch(sql,/\bJOIN owned_team\b/)
 const executable=sql.replace(/^\s*--[^\r\n]*/gm,'')
 assert.doesNotMatch(executable,/\b(?:GRANT|INSERT|UPDATE|DELETE|CREATE|ALTER)\s/i)
})
test('Squad screen is a separate read-only page and refuses synthetic fallback',()=>{
 assert.match(client,/path="\/dashboard\/squad" element=\{<SquadPreview/)
 assert.match(client,/request\('squad'\)/)
 assert.match(client,/isSyntheticSquad\(packet,expected\)/)
 assert.match(client,/data-squad-table/)
 assert.match(client,/data-squad-state=\{state\}/)
 assert.match(client,/No fixture roster is displayed/)
 assert.match(client,/Original-game fields including role, age, overall, fatigue/)
 assert.doesNotMatch(client,/request\('squad','POST'/)
})
