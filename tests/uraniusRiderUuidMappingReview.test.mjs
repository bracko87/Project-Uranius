import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const p=new URL('../database/reconstruction/squad/014_synthetic_rider_uuid_REVIEW_ONLY.sql',import.meta.url)
const sql=readFileSync(p,'utf8')
test('014 is isolated, review-only and keeps historic 013 ledger unchanged',()=>{
 assert.match(sql,/REVIEW ONLY \/ NOT APPROVED/)
 assert.match(sql,/uranius\.approved_project_ref/)
 assert.match(sql,/sdtsivgtcaoaeoihcwzd/)
 assert.match(sql,/current_user <> 'uranius_migrator'/)
 assert.match(sql,/pg_stat_ssl/)
 assert.match(sql,/\(SELECT count\(\*\) FROM uranius_private\.migration_ledger\) <> 11/)
 assert.match(sql,/013_squad_reader_grant\.sql/)
 assert.match(sql,/8193d80743f6392709a3220441531636751a70fc487c111cc23d1865080be859/)
 assert.doesNotMatch(sql.replace(/^\s*--[^\r\n]*/gm,''),/\bCOMMIT\s*;/i)
})
test('014 adds ONLY synthetic UUID mapping with source FK, unique UUID and synthetic provenance',()=>{
 assert.match(sql,/CREATE TABLE uranius_game\.synthetic_rider_identity/)
 assert.match(sql,/rider_id integer PRIMARY KEY REFERENCES uranius_catalog\.riders\(rider_id\) ON DELETE RESTRICT/)
 assert.match(sql,/rider_uuid uuid NOT NULL DEFAULT pg_catalog\.gen_random_uuid\(\) UNIQUE/)
 assert.match(sql,/identity_provenance text NOT NULL DEFAULT 'uranius_generated_synthetic'/)
 assert.match(sql,/INSERT INTO uranius_game\.synthetic_rider_identity\(rider_id\)/)
 assert.match(sql,/SELECT rider_id FROM uranius_catalog\.riders ORDER BY rider_id/)
 assert.doesNotMatch(sql,/\bUPDATE\s+uranius_catalog\.riders\b/i)
 assert.doesNotMatch(sql,/\bALTER\s+TABLE\s+uranius_catalog\.riders\b/i)
})
test('014 has fail-closed row-level restrictions with no new public API grants',()=>{
 assert.match(sql,/REVOKE ALL ON uranius_game\.synthetic_rider_identity FROM PUBLIC, anon, authenticated, uranius_smoke_reader/)
 assert.match(sql,/ENABLE ROW LEVEL SECURITY/)
 assert.match(sql,/FORCE ROW LEVEL SECURITY/)
 assert.match(sql,/pg_policies/)
 assert.match(sql,/has_any_column_privilege\('anon','uranius_game\.synthetic_rider_identity','SELECT'\)/)
 assert.match(sql,/has_any_column_privilege\('uranius_smoke_reader','uranius_game\.synthetic_rider_identity','SELECT'\)/)
 const executable=sql.replace(/^\s*--[^\r\n]*/gm,'')
 assert.doesNotMatch(executable,/\bGRANT\s+(?:SELECT|ALL)\b/i)
 assert.doesNotMatch(executable,/\bSECURITY DEFINER\b/i)
 assert.doesNotMatch(executable,/\bCREATE\s+(?:POLICY|VIEW|FUNCTION)\b/i)
})
test('014 checks that all 200 identities exist before FORCE RLS blocks even owner reads',()=>{
 const insert=sql.indexOf('INSERT INTO uranius_game.synthetic_rider_identity(rider_id)')
 const verify=sql.indexOf('DO $rider014_insert_verify$')
 const force=sql.indexOf('FORCE ROW LEVEL SECURITY')
 assert.ok(insert>0 && verify>insert && force>verify)
 assert.match(sql,/count\(DISTINCT rider_uuid\)/)
 assert.match(sql,/EXCEPT SELECT rider_id/)
 assert.match(sql,/relforcerowsecurity/)
})
