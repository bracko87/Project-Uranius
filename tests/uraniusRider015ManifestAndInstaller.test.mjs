import assert from 'node:assert/strict'
import {createHash} from 'node:crypto'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const base=new URL('../database/reconstruction/squad/',import.meta.url)
const get=n=>readFileSync(new URL(n,base))
const sha=x=>createHash('sha256').update(x).digest('hex')
const mBytes=get('015_install_manifest_REVIEW_ONLY.json'),m=JSON.parse(mBytes)
const prior=JSON.parse(get('014_install_manifest_REVIEW_ONLY.json'))
const candidate=get('015_rider_uuid_owner_read_REVIEW_ONLY.sql')
const installer=readFileSync(new URL('../scripts/apply-uranius-rider-015.mjs',import.meta.url),'utf8')
test('015 exact native-reviewed SQL and manifest are frozen and not approved',()=>{
 assert.equal(sha(candidate),'71ade068c5cf5bbdc0e356663a0525f1e74b43e63a9c19f267748f7b46b6161e')
 assert.equal(sha(mBytes),'f9d835dd58c242d83b7366976810be1eb0525d9e2c401e361ef7b6d66e76ec81')
 assert.equal(m.candidate.sha256,sha(candidate))
 assert.equal(m.projectRef,'sdtsivgtcaoaeoihcwzd')
 assert.equal(m.postgresMajor,17)
 assert.equal(m.expectedLedgerEntries,12)
 assert.equal(m.status,'REVIEW_ONLY_NOT_APPROVED')
 assert.equal(m.approvalRequired,true)
 assert.equal(m.hostedApplied,false)
})
test('015 historical freeze contains exact 001–010 013 and installed 014 digests',()=>{
 assert.equal(m.requires.length,12)
 assert.deepEqual(m.requires.slice(0,11),prior.requires)
 assert.deepEqual(m.requires[11],{file:prior.candidate.ledgerVersion,sha256:prior.candidate.sha256})
 assert.equal(new Set(m.requires.map(r=>r.file)).size,12)
 assert.ok(m.requires.every(r=>/^[a-f0-9]{64}$/.test(r.sha256)))
})
test('015 guarded installer requires separate approved hash, direct migrator TLS and atomic batch',()=>{
 assert.match(installer,/if\(approvedDigest!==exactManifest\)/)
 assert.match(installer,/assertSandboxTarget\('migrate',env\)/)
 assert.match(installer,/PGUSER:'uranius_migrator'/)
 assert.match(installer,/PGSSLMODE:'verify-full'/)
 assert.match(installer,/PGGSSENCMODE:'disable'/)
 assert.match(installer,/runPsqlBatch\(\{executable:env\.URANIUS_PSQL_PATH,input:sql,env:child,transaction:true/)
 assert.match(installer,/--apply-approved-015/)
 assert.match(installer,/--review/)
})
test('015 installer checks all 12 ledger fingerprints in both directions, writes 13th and verifies RLS',()=>{
 assert.match(installer,/JSON\.stringify\(manifest\.requires\)!==JSON\.stringify\(history\)/)
 assert.match(installer,/EXCEPT SELECT version,sha256 FROM uranius_private\.migration_ledger/)
 assert.match(installer,/EXCEPT SELECT version,sha256 FROM \(VALUES/)
 assert.match(installer,/history\.length/)
 assert.match(installer,/INSERT INTO uranius_private\.migration_ledger\(version,sha256\)/)
 assert.match(installer,/count\(\*\) FROM uranius_private\.migration_ledger\)<>13/)
 assert.match(installer,/relrowsecurity AND relforcerowsecurity/)
 assert.match(installer,/has_any_column_privilege\('anon'/)
 assert.match(installer,/has_any_column_privilege\('authenticated'/)
 assert.match(installer,/identity_provenance','SELECT'/)
 assert.match(installer,/created_at','SELECT'/)
 assert.match(installer,/team_id','SELECT'/)
 assert.match(installer,/is_paused/)
})
test('015 source scope is only one policy and two column grants',()=>{
 const sql=candidate.toString('utf8').replace(/^\s*--[^\r\n]*/gm,'')
 assert.match(sql,/CREATE POLICY synthetic_rider_uuid_owner_read/)
 assert.match(sql,/GRANT SELECT \(rider_id,rider_uuid\)/)
 assert.doesNotMatch(sql,/\bCREATE VIEW\b|\bSECURITY DEFINER\b/i)
 assert.doesNotMatch(sql,/\bGRANT SELECT ON\b|\bGRANT ALL\b/i)
 // Match executable write statements, not quoted privilege names such as 'UPDATE'.
 assert.doesNotMatch(sql,/^\s*(?:ALTER\s+TABLE\b|UPDATE\s+|DELETE\s+FROM\b)/im)
 assert.match(sql,/has_table_privilege\('uranius_smoke_reader','uranius_game\.synthetic_rider_identity','UPDATE'\)/)
})
