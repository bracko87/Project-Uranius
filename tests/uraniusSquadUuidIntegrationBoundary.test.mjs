import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const sql=read('database/synthetic-world/hosted-squad-uuid-read_REVIEW_ONLY.sql')
const server=read('scripts/run-uranius-hosted-smoke.mjs')
const adapter=read('database/synthetic-world/club-dashboard-adapter.mjs')
const client=read('database/synthetic-world/hosted-smoke-client.tsx')
const launcher=read('scripts/run-approved-overview-https-windows.ps1')
test('UUID Squad SQL remains TLS-guarded, read-only and double RLS-filtered',()=>{
 assert.match(sql,/BEGIN READ ONLY;/)
 assert.match(sql,/ROLLBACK;\s*$/)
 assert.match(sql,/current_user <> 'uranius_smoke_reader'/)
 assert.match(sql,/session_user <> current_user/)
 assert.match(sql,/pg_stat_ssl/)
 assert.match(sql,/get_my_club_id\(\) IS NULL/)
 assert.match(sql,/jsonb_build_object\('sub',:'verified_subject'\)/)
 assert.match(sql,/FROM uranius_catalog\.riders r/)
 assert.match(sql,/LEFT JOIN uranius_game\.synthetic_rider_identity m ON m\.rider_id = r\.rider_id/)
 assert.match(sql,/'syntheticRiderUuid',rider_uuid::text/)
 assert.match(sql,/'kind','syntheticSquadUuidPreview'/)
 const statements=sql.replace(/^\s*--[^\r\n]*/gm,'')
 assert.doesNotMatch(statements,/^\s*(?:GRANT|REVOKE|INSERT|UPDATE|DELETE|CREATE|ALTER)\s/im)
 assert.doesNotMatch(statements,/\bSECURITY\s+DEFINER\b/i)
})
test('015 UUID route is opt-in and only receives backend-verified manager subject',()=>{
 assert.match(server,/URANIUS_SQUAD_UUID_READ_APPROVED === '1'/)
 assert.match(server,/readSquadUuid: squadUuidSql \? \(id\) =>/)
 assert.match(server,/input: '\\\\set verified_subject ' \+ id \+ '\\n' \+ squadUuidSql/)
 assert.match(server,/PGUSER: 'uranius_smoke_reader'/)
 assert.match(server,/PGSSLMODE: 'verify-full'/)
 assert.match(adapter,/readSquadUuid\(current\.subject\)/)
 assert.match(adapter,/projectSyntheticSquadUuidPreview\(result, \{ ownerVerified: true \}\)/)
 assert.match(adapter,/UUID Squad preview not connected/)
 assert.match(launcher,/URANIUS_SQUAD_UUID_READ_APPROVED = '1'/)
 assert.match(launcher,/URANIUS_SQUAD_UUID_READ_APPROVED'\)/)
})
test('Squad UI prefers UUID response but preserves non-UUID read-only legacy path',()=>{
 assert.match(client,/request\('squad-uuid'\)\.then\(packet => packet \?\? request\('squad'\)\)/)
 assert.match(client,/kind === 'syntheticSquadUuidPreview'/)
 assert.match(client,/data-synthetic-rider-uuid/)
 assert.match(client,/Uranius synthetic UUID:/)
 assert.match(client,/not an original rider UUID/)
 assert.match(client,/Original-game fields including role, age, overall, fatigue/)
 assert.doesNotMatch(client,/request\('squad-uuid','POST'/)
})
