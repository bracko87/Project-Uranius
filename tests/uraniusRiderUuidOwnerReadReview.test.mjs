import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {test} from 'node:test'
const src=readFileSync(new URL('../database/reconstruction/squad/015_rider_uuid_owner_read_REVIEW_ONLY.sql',import.meta.url),'utf8')
const stmt=src.replace(/^\s*--[^\r\n]*/gm,'')
test('015 is review-only and targets exact installed 014 and isolated TLS migrator',()=>{
 assert.match(src,/REVIEW ONLY/)
 assert.match(src,/DO NOT RUN AGAINST HOSTED DATABASE/)
 assert.match(src,/sdtsivgtcaoaeoihcwzd/)
 assert.match(src,/current_user <> 'uranius_migrator'/)
 assert.match(src,/session_user <> current_user/)
 assert.match(src,/pg_stat_ssl/)
 assert.match(src,/migration_ledger\)<>12/)
 assert.match(src,/014_synthetic_rider_uuid\.sql/)
 assert.match(src,/f97126ed0a9259bfeac9ebf3c4158ece7a590b3ae77fd7d66f7efdc26894db6f/)
})
test('015 RLS ownership is evaluated via existing restricted rider policy, not user-supplied team IDs',()=>{
 assert.match(src,/CREATE POLICY synthetic_rider_uuid_owner_read/)
 assert.match(src,/FOR SELECT TO uranius_smoke_reader/)
 assert.match(src,/SELECT 1 FROM uranius_catalog\.riders AS own_rider/)
 assert.match(src,/own_rider\.rider_id = synthetic_rider_identity\.rider_id/)
 assert.match(src,/policyname='riders_read'/)
 assert.match(src,/qual LIKE '%request_uid\(\)%'/)
 assert.doesNotMatch(stmt,/request\.jwt\.claim\.sub.*=.*team_id/)
 assert.doesNotMatch(stmt,/\bSECURITY DEFINER\b/i)
})
test('015 reader only receives UUID and rider integer ID, no hidden provenance, team ID or write capability',()=>{
 assert.match(src,/GRANT SELECT \(rider_id,rider_uuid\)/)
 assert.match(src,/GRANT SELECT \(rider_id,rider_uuid\)\s+ON uranius_game\.synthetic_rider_identity TO uranius_smoke_reader/)
 assert.match(src,/identity_provenance','SELECT'\)/)
 assert.match(src,/created_at','SELECT'\)/)
 assert.match(src,/team_id','SELECT'\)/)
 assert.match(src,/has_any_column_privilege\('anon'/)
 assert.match(src,/has_any_column_privilege\('authenticated'/)
 assert.match(src,/has_table_privilege\('uranius_smoke_reader'.*'INSERT'/)
 assert.match(src,/has_table_privilege\('uranius_smoke_reader'.*'UPDATE'/)
 assert.match(src,/has_table_privilege\('uranius_smoke_reader'.*'DELETE'/)
 assert.doesNotMatch(stmt,/GRANT (?:ALL|INSERT|UPDATE|DELETE)/)
 assert.doesNotMatch(stmt,/GRANT SELECT ON/)
})
test('015 preserves existing 014 FORCE RLS and does not mutate canonical riders',()=>{
 assert.match(src,/relrowsecurity AND relforcerowsecurity/)
 assert.match(src,/count\(\*\) FROM uranius_catalog\.riders\)<>200/)
 assert.match(src,/count\(\*\) FROM uranius_catalog\.team_owners\)<>2/)
 assert.match(src,/count\(\*\) FROM uranius_private\.migration_ledger\)<>12/)
 assert.doesNotMatch(stmt,/\bALTER TABLE uranius_catalog\.riders\b/i)
 assert.doesNotMatch(stmt,/\bUPDATE\s+uranius_catalog\.riders\b/i)
 assert.doesNotMatch(stmt,/\bINSERT\s+INTO\s+uranius_catalog\.riders\b/i)
 assert.doesNotMatch(stmt,/\b(?:BEGIN|COMMIT|ROLLBACK)\s*;/i)
})
