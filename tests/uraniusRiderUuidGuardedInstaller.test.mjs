 assert.match(code,/hash\(manifestBytes\)!==expectedManifestHash/)
 assert.match(code,/hash\(bytes\)!==expectedCandidateHash/)
 assert.match(code,/if\(digest!==expectedManifestHash\)/)
 assert.match(code,/--apply-approved-014/)
