import assert from 'node:assert/strict'
import {test} from 'node:test'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
const read=n=>readFileSync(new URL('../'+n,import.meta.url),'utf8')
const script=read('scripts/apply-uranius-rider-018.mjs')
const launch=read('scripts/run-approved-rider-018-windows.ps1')
const candidate=readFileSync(new URL('../database/reconstruction/squad/018_synthetic_nine_skill_attributes_REVIEW_ONLY.sql',import.meta.url))
const manifestBytes=readFileSync(new URL('../database/reconstruction/squad/018_install_manifest_REVIEW_ONLY.json',import.meta.url))
const manifest=JSON.parse(manifestBytes)
const prior=JSON.parse(read('database/reconstruction/squad/015_install_manifest_REVIEW_ONLY.json'))
test('018 hashes and all thirteen historical prerequisites are frozen and NOT approved',()=>{
 assert.equal(createHash('sha256').update(candidate).digest('hex'),'622d7626f5f6d93117cbb755398971d23ca0a870e49bc8c98e2df768630b48cc')
 assert.equal(createHash('sha256').update(manifestBytes).digest('hex'),'9995c7a1558d222426e759b5af4911981d5d4b12688a4e2e3c1adee8d6975205')
 assert.equal(manifest.status,'REVIEW_ONLY_NOT_APPROVED')
 assert.equal(manifest.hostedApplied,false)
 assert.equal(manifest.approvalRequired,true)
 assert.equal(manifest.projectRef,'sdtsivgtcaoaeoihcwzd')
 assert.deepEqual(manifest.requires,[...prior.requires,{file:prior.candidate.ledgerVersion,sha256:prior.candidate.sha256}])
 assert.equal(manifest.requires.length,13)
 assert.equal(manifest.expectedLedgerEntries,13)
})
test('018 installer is exact digest, direct-TLS restricted migrator and atomic transaction only',()=>{
 assert.match(script,/--apply-approved-018/)
 assert.match(script,/manifestHash='9995c7a1558d222426e759b5af4911981d5d4b12688a4e2e3c1adee8d6975205'/)
 assert.match(script,/if\(approved!==manifestHash\)/)
 assert.match(script,/assertSandboxTarget\('migrate',env\)/)
 assert.match(script,/PGUSER:'uranius_migrator'/)
 assert.match(script,/PGSSLMODE:'verify-full'/)
 assert.match(script,/PGSSLROOTCERT:env.URANIUS_DATABASE_CA_FILE/)
 assert.match(script,/transaction:true/)
 assert.doesNotMatch(script,/PGUSER:'postgres'|PGSSLMODE:'disable'|service_role/)
})
test('018 compares all historical ledger version-hash pairs bidirectionally, writes 14th only inside transaction',()=>{
 assert.match(script,/JSON\.stringify\(manifest\.requires\)!==JSON\.stringify\(history\)/)
 assert.match(script,/SELECT version,sha256 FROM \(VALUES /)
 assert.match(script,/EXCEPT SELECT version,sha256 FROM uranius_private\.migration_ledger/)
 assert.match(script,/EXCEPT SELECT version,sha256 FROM \(VALUES /)
 assert.match(script,/INSERT INTO uranius_private\.migration_ledger\(version,sha256\) VALUES \('018_synthetic_nine_skill_attributes\.sql'/)
 assert.match(script,/count\(\*\) FROM uranius_private\.migration_ledger\)<>14/)
 assert.match(script,/count\(\*\) FROM pg_constraint .*contype='c'\)<>27/)
 assert.match(script,/relrowsecurity AND relforcerowsecurity/)
 assert.match(script,/synthetic_rider_identity/)
 assert.match(script,/has_any_column_privilege\('uranius_smoke_reader','uranius_game\.synthetic_rider_attributes','SELECT'\)/)
 assert.match(script,/game_state WHERE is_paused/)
})
test('018 Windows launcher requires exact hash, offline review, local confirmation, private password and cleans credentials',()=>{
 assert.match(launch,/9995c7a1558d222426e759b5af4911981d5d4b12688a4e2e3c1adee8d6975205/)
 assert.match(launch,/apply-uranius-rider-018\.mjs/)
 assert.match(launch,/--review/)
 assert.match(launch,/APPLY URANIUS 018/)
 assert.match(launch,/-AsSecureString/)
 assert.match(launch,/--apply-approved-018/)
 assert.match(launch,/uranius_migrator/)
 assert.match(launch,/ZeroFreeBSTR/)
 assert.match(launch,/Remove-Item "Env:\$name"/)
 assert.ok(launch.indexOf('& node $script --review')<launch.indexOf("Read-Host 'Type APPLY URANIUS 018"))
 assert.ok(launch.indexOf("Read-Host 'Type APPLY URANIUS 018")<launch.indexOf('Read-Host \'Dedicated Uranius migrator password'))
})
